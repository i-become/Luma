-- =============================================
-- Luma 权限管理系统 - 添加菜单默认展开字段
-- 版本: 1.0.0
-- 说明: 为 sys_menu 表添加 always_show 字段，用于控制目录类型菜单是否默认展开
-- =============================================

-- 添加 always_show 字段
ALTER TABLE sys_menu ADD COLUMN always_show TINYINT(1) DEFAULT 0 COMMENT '是否默认展开(仅目录类型有效): 0-否 1-是' AFTER hidden;

-- 更新现有数据：将所有目录类型的菜单设置为不默认展开
UPDATE sys_menu SET always_show = 0 WHERE type = 'M';

-- =============================================
-- 字段说明
-- =============================================
-- always_show: 是否默认展开
--   0 - 不展开（默认）
--   1 - 默认展开
-- 仅对目录类型（type='M'）的菜单有效
-- 当设置为1时，左侧菜单会默认展开该目录的子菜单

-- =============================================
-- 使用示例
-- =============================================
-- 设置"系统管理"目录默认展开
-- UPDATE sys_menu SET always_show = 1 WHERE id = 1 AND type = 'M';
